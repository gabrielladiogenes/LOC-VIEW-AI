def search_location_ui(raw, postal):

    try:

        parsed = parse_address(raw)
        postal_code = postal_input(postal)

        if (
            postal_code
            and parsed["postal_code"]
            and postal_code != parsed["postal_code"]
        ):

            return panel(
                "Conflicting postal codes",
                "The address and Postal code field "
                "contain different values."
            )

        if postal_code:
            parsed["postal_code"] = postal_code

    except ValueError as error:

        return panel(
            str(error)
        )

    state = STATES.get(
        parsed["state"].upper(),
        parsed["state"]
    )

    base = (
        f"{parsed['street']}, "
        f"{parsed['number']}, "
        f"{parsed['city']}, "
        f"{state}, Brasil"
    )

    queries = [
        {
            "q": base
        },

        {
            "q": (
                f"{parsed['number']} "
                f"{parsed['street']}, "
                f"{parsed['city']}, "
                f"{state}, Brasil"
            )
        },

        {
            "street": (
                f"{parsed['number']} "
                f"{parsed['street']}"
            ),
            "city": parsed["city"],
            "state": state,
            "country": "Brasil"
        }
    ]

    if parsed["postal_code"]:

        queries.insert(
            0,
            {
                "q": (
                    f"{parsed['street']}, "
                    f"{parsed['number']}, "
                    f"{parsed['city']}, "
                    f"{state}, "
                    f"{parsed['postal_code']}, "
                    "Brasil"
                )
            }
        )

    exact_results = []
    street_results = []

    try:

        for query in queries:

            rows = search_api(query)

            exact_results.extend(rows)

            matches = [
                row
                for row in rows
                if check(
                    row,
                    parsed,
                    exact=True
                )
            ]

            if matches:

                return success_panel(
                    matches[0],
                    parsed
                )

        street_queries = [
            {
                "q": (
                    f"{parsed['street']}, "
                    f"{parsed['city']}, "
                    f"{state}, Brasil"
                )
            },

            {
                "street": parsed["street"],
                "city": parsed["city"],
                "state": state,
                "country": "Brasil"
            }
        ]

        for query in street_queries:

            rows = search_api(query)
            street_results.extend(rows)

    except requests.RequestException:

        return panel(
            "Search temporarily unavailable",
            "Please try again in a moment.",
            "bad"
        )

    matches = [
        row
        for row in (
            exact_results
            + street_results
        )
        if check(
            row,
            parsed,
            exact=False
        )
    ]

    if matches:

        return panel(
            "Street located — house number not confirmed",

            (
                f"{matches[0].get('display_name', '')}\n"
                f"Requested house number: "
                f"{parsed['number']}.\n"
                "The exact building location "
                "could not be verified."
            )
        )

    return panel(
        "Location not found",

        (
            "The requested address could not "
            "be confirmed in the available map data. "
            "This does not mean it does not exist."
        )
    )


