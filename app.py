def search_api(params):

    with LOCK:

        elapsed = (
            time.monotonic()
            - LAST_REQUEST[0]
        )

        wait = 1.15 - elapsed

        if wait > 0:
            time.sleep(wait)

        LAST_REQUEST[0] = time.monotonic()

        response = SESSION.get(
            API,
            params={
                "format": "jsonv2",
                "addressdetails": 1,
                "limit": 20,
                "countrycodes": "br",
                **params
            },
            headers={
                "User-Agent": USER_AGENT
            },
            timeout=25
        )

        response.raise_for_status()

    return response.json()


def fields(result):

    address = result.get(
        "address"
    ) or {}

    street = next(
        (
            address[key]
            for key in (
                "road",
                "pedestrian",
                "residential",
                "footway",
                "street",
                "square"
            )
            if address.get(key)
        ),
        ""
    )

    city = next(
        (
            address[key]
            for key in (
                "city",
                "town",
                "municipality",
                "village"
            )
            if address.get(key)
        ),
        ""
    )

    return {
        "street": street,

        "number": str(
            address.get(
                "house_number",
                ""
            )
        ).upper().strip(),

        "city": city,

        "state": address.get(
            "state",
            ""
        ),

        "country": address.get(
            "country_code",
            ""
        ),

        "postal": re.sub(
            r"\D",
            "",
            address.get(
                "postcode",
                ""
            )
        )
    }


def check(result, parsed, exact=False):

    address = fields(result)

    if address["country"] != "br":
        return False

    if norm(
        address["city"]
    ) != norm(
        parsed["city"]
    ):
        return False

    if canonical_state(
        address["state"]
    ) != canonical_state(
        parsed["state"]
    ):
        return False

    if not street_equal(
        address["street"],
        parsed["street"]
    ):
        return False

    if exact:

        if norm(
            address["number"]
        ) != norm(
            parsed["number"]
        ):
            return False

        if (
            parsed["postal_code"]
            and address["postal"]
            and parsed["postal_code"]
            != address["postal"]
        ):
            return False

    return True


