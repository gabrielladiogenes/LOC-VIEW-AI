def links(parsed, result):

    latitude = result["lat"]
    longitude = result["lon"]

    address_text = (
        f"{parsed['street']}, "
        f"{parsed['number']}, "
        f"{parsed['city']}, "
        f"{parsed['state']}, Brasil"
    )

    maps_url = (
        "https://www.google.com/maps/search/"
        "?api=1&query="
        + quote(address_text)
    )

    street_view_url = (
        "https://www.google.com/maps/@?"
        + urlencode({
            "api": "1",
            "map_action": "pano",
            "viewpoint": (
                f"{latitude},{longitude}"
            )
        })
    )

    return maps_url, street_view_url


