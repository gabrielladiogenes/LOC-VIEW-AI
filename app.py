def postal_input(value):

    value = (value or "").strip()

    if not value:
        return ""

    if not re.fullmatch(
        r"\d{5}-?\d{3}",
        value
    ):

        raise ValueError(
            "Invalid postal code. "
            "Use 8 digits, e.g., 60840-000."
        )

    return re.sub(
        r"\D",
        "",
        value
    )


