def norm(value):

    value = unicodedata.normalize(
        "NFKD",
        str(value or "")
    )

    value = "".join(
        char
        for char in value
        if not unicodedata.combining(char)
    )

    return re.sub(
        r"\s+",
        " ",
        re.sub(
            r"[^a-z0-9]+",
            " ",
            value.lower()
        )
    ).strip()


def normalize_street(value):

    value = norm(value)

    value = re.sub(
        r"^r\b",
        "rua",
        value
    )

    value = re.sub(
        r"^av\b",
        "avenida",
        value
    )

    words = value.split()

    result = []
    i = 0

    while i < len(words):

        if words[i] in NUMWORDS:

            number = NUMWORDS[words[i]]
            j = i + 1

            if (
                number >= 20
                and number % 10 == 0
                and j + 1 < len(words)
                and words[j] == "e"
                and words[j + 1] in NUMWORDS
                and NUMWORDS[words[j + 1]] < 10
            ):

                number += NUMWORDS[
                    words[j + 1]
                ]

                j += 2

            result.append(str(number))
            i = j

        else:

            result.append(words[i])
            i += 1

    return " ".join(result)


def street_equal(a, b):

    x = normalize_street(a)
    y = normalize_street(b)

    if not x or not y:
        return False

    if x == y:
        return True

    return (
        len(x) > 10
        and len(y) > 10
        and SequenceMatcher(
            None,
            x,
            y
        ).ratio() >= 0.94
    )


def canonical_state(value):

    key = norm(value)

    for abbreviation, full_name in STATES.items():

        if key in (
            norm(abbreviation),
            norm(full_name)
        ):
            return norm(full_name)

    return key


