def parse_address(raw):

    raw = re.sub(
        r"\s+",
        " ",
        (raw or "").strip()
    )

    if not raw:

        raise ValueError(
            "Enter a complete address."
        )

    postal_matches = re.findall(
        r"(?<!\d)\d{5}-?\d{3}(?!\d)",
        raw
    )

    postal_matches = [
        re.sub(r"\D", "", item)
        for item in postal_matches
    ]

    if len(set(postal_matches)) > 1:

        raise ValueError(
            "Conflicting postal codes were "
            "found in the address."
        )

    postal_code = (
        postal_matches[0]
        if postal_matches
        else ""
    )

    clean = re.sub(
        r"(?<!\d)\d{5}-?\d{3}(?!\d)",
        "",
        raw
    )

    clean = re.sub(
        r"\s*/\s*",
        " / ",
        clean
    )

    clean = re.sub(
        r"\s*,\s*",
        ", ",
        clean
    )

    clean = re.sub(
        r"\s*,\s*,+",
        ",",
        clean
    ).strip(" ,-")

    parts = [
        part.strip(" ,")
        for part in clean.split(",")
        if part.strip(" ,")
    ]

    if not parts:

        raise ValueError(
            "Enter a street and an exact house number."
        )

    street = parts[0]
    number = ""
    tail = parts[1:]

    # Identify house number without treating
    # numbers in street names as house numbers.

    match = re.search(
        r"(?:,\s*|\s+(?:n[º°.]?|numero|número)\s*)"
        r"(\d+[A-Za-z]?)\b",
        clean,
        re.I
    )

    if (
        match
        and match.start() < len(parts[0]) + 5
    ):

        number = match.group(1)

        if re.search(
            r"\d+[A-Za-z]?\s*$",
            parts[0]
        ):

            street = re.sub(
                r"\s+(?:n[º°.]?|numero|número)?"
                r"\s*\d+[A-Za-z]?\s*$",
                "",
                parts[0],
                flags=re.I
            )

        elif (
            tail
            and re.fullmatch(
                r"\d+[A-Za-z]?(?:\s*-.*)?",
                tail[0]
            )
        ):

            tail.pop(0)

    if not number and tail:

        number_match = re.match(
            r"^(\d+[A-Za-z]?)"
            r"(?:\s*-\s*(.*))?$",
            tail[0]
        )

        if number_match:

            number = number_match.group(1)

            remainder = (
                number_match.group(2) or ""
            ).strip()

            tail = (
                [remainder]
                if remainder
                else []
            ) + tail[1:]

    if not number:

        number_match = re.search(
            r"\s+(\d+[A-Za-z]?)$",
            street
        )

        if number_match:

            number = number_match.group(1)

            street = street[
                :number_match.start()
            ].strip()

    if not number:

        raise ValueError(
            "Enter the exact house number. "
            "The address does not include one."
        )

    if not re.match(
        r"(?i)^(?:rua\b|r\.(?=\s)|"
        r"avenida\b|av\.(?=\s)|"
        r"travessa\b|alameda\b|"
        r"praca\b|praça\b|"
        r"estrada\b|rodovia\b|"
        r"largo\b|viela\b)",
        street
    ):

        raise ValueError(
            "Enter the street type and name "
            "(e.g., Rua or Avenida)."
        )

    extra = ", ".join(tail)

    extra = re.sub(
        r"\s*/\s*",
        ", ",
        extra
    )

    extra = re.sub(
        r"\s+-\s+(?=[A-Za-zÀ-ÿ ]+\s*(?:,|$))",
        ", ",
        extra
    )

    locations = [
        item.strip()
        for item in extra.split(",")
        if item.strip()
    ]

    locations = [
        item
        for item in locations
        if norm(item) not in (
            "brasil",
            "brazil"
        )
    ]

    state = ""
    city = ""
    neighborhood = ""

    valid_states = {
        norm(value)
        for value in STATES.values()
    }

    state_index = next(
        (
            index
            for index in range(
                len(locations) - 1,
                -1,
                -1
            )
            if canonical_state(
                locations[index]
            ) in valid_states
        ),
        None
    )

    if state_index is not None:

        state = locations[state_index]

        if state_index >= 1:
            city = locations[state_index - 1]

        if state_index >= 2:
            neighborhood = locations[
                state_index - 2
            ]

    elif locations:

        city = locations[-1]

        if len(locations) > 1:
            neighborhood = locations[-2]

    if not city:

        raise ValueError(
            "Enter the city and state "
            "(e.g., Fortaleza, CE)."
        )

    if not state:

        raise ValueError(
            "Enter the state (e.g., CE or SP)."
        )

    return {
        "street": street.strip(),
        "number": number.upper(),
        "city": city,
        "state": state,
        "neighborhood": neighborhood,
        "postal_code": postal_code
    }


